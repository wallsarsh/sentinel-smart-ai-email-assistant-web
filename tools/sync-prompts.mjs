// Regenerates server/ai/prompts/texts.generated.ts from docs/reference/ai-prompts.md.
// The document is the reviewed source; a test fails when the two disagree.
import { readFileSync, writeFileSync } from 'node:fs'

export function extract(doc) {
  const sections = Object.fromEntries(doc.split(/\n(?=## )/).map((s) => [s.split('\n', 1)[0], s]))
  const sec = (prefix) => {
    const k = Object.keys(sections).find((x) => x.startsWith(prefix))
    if (!k) throw new Error(`section ${prefix} not found`)
    return sections[k]
  }
  const blocks = (s) => [...s.matchAll(/```(\w+)\n([\s\S]*?)```/g)].map((m) => m[2])
  const [t, b, d, r] = [sec('## 2.'), sec('## 3.'), sec('## 4.'), sec('## 5.')].map(blocks)
  return {
    triageSystem: t[0].replace(/\n+$/, ''),
    triageSchemaJson: JSON.stringify(JSON.parse(t[1]), null, 2),
    briefSystem: b[0].replace(/\n+$/, ''),
    briefSchemaJson: JSON.stringify(JSON.parse(b[2]), null, 2),
    draftSystem: d[0].replace(/\n+$/, ''),
    repairTemplate: r[0].replace(/\n+$/, ''),
  }
}

export function render(items) {
  const lines = [
    '// GENERATED by tools/sync-prompts.mjs from docs/reference/ai-prompts.md. Do not edit.',
    '',
  ]
  for (const [name, value] of Object.entries(items))
    lines.push(`export const ${name} = ${JSON.stringify(value)}`, '')
  return lines.join('\n')
}

if (import.meta.url === `file://${process.argv[1]}`)
  writeFileSync(
    'server/ai/prompts/texts.generated.ts',
    render(extract(readFileSync('docs/reference/ai-prompts.md', 'utf8'))),
  )
